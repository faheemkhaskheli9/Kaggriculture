    return {
        "mode": selected,
        "config": config,
        "max_quadrants": int(config.get("MAX_QUADRANTS", common["MAX_QUADRANTS"])),
        "max_hands": int(config.get("MAX_HANDS", common["MAX_HANDS"])),
        "feed_stock_days": int(config.get("FEED_STOCK_DAYS", 2)),
    }
