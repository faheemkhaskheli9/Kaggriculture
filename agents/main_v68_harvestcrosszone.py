# OPP_SHADE (Lever G, docs/PLAN_LADDER_NEXT_5 + docs/RESEARCH_LADDER_META C4:
# Halite 1st place's decisive lever was per-opponent online modeling). The
# opponent's whole farm is public in obs["farms"]; classify it once per turn
# from visible state and *shade* our sell sizing (never flip strategy -- the
# one prior passive/active flip regressed on a crude detector). ON: for a shed
# product the opponent is visibly about to flood (their standing crop tiles of
