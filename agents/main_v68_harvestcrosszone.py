def _idle_seed_shortfall(obs, me, seeds, intent=None):
    """Unlocked, non-shed, non-animal-reserved empty tiles beyond the seeds
    already on hand (any crop) -- the tiles that will stay idle for lack of
    seed, not for lack of hands or space."""
    tiles = me.get("tiles", [])
    idle = sum(1 for y, row in enumerate(tiles) for x, t in enumerate(row)
               if t is None and (x, y) not in SHED_TILES)
    if USE_ANIMALS:
        tgt = animal_targets(obs, me, intent)
        placed = sum(_placed_animal_counts(me).values())
        idle -= max(0, sum(tgt.values()) - placed)
    on_hand = sum(int(seeds.get(c, 0)) for c in CROPS)
    return max(0, idle - on_hand)


