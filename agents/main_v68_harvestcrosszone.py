def _terminal_jobs(obs, me):
    """Harvestable stock and available fertilizer for final-day collection."""
    jobs = []
    prices = (obs.get("market") or {}).get("prices", {})
    for y, row in enumerate(me["tiles"]):
        for x, tile in enumerate(row):
            if not isinstance(tile, dict):
                continue
            target = (x, y)
            product = tile.get("crop")
            if product in CROPS:
                age = int(obs.get("day", 0)) - int(tile.get("planted_day", 0))
                if age < CROPS[product][1]:
                    continue  # Positive starting yield is not yet harvestable.
            if tile.get("animal") in ANIMALS:
                product = ANIMALS[tile["animal"]][5]
            quantity = max(0, int(tile.get("yield_units", 0)))
            if product in BASE and quantity:
                value = quantity * max(1, int(prices.get(product, BASE[product])))
                jobs.append((value, target, ["HARVEST"]))
            if tile.get("animal") and tile.get("fertilizer_available", False):
                value = max(1, int(prices.get("FERTILIZER", BASE["FERTILIZER"])))
                jobs.append((value, target, ["COLLECT_FERTILIZER"]))
    return jobs


def _terminal_assign(obs, me, private):
    """Collect stock only when its return and same-turn sale can still finish."""
    positions = [tuple(me["farmer"])] + [tuple(p) for p in me.get("hands", [])]
    invs = list(private.get("inventories", []) or [])
    invs += [{} for _ in range(len(positions) - len(invs))]
    remaining = max(0, TERMINAL_LAST_HOUR + 1 - int(obs.get("hour", 0)))
    actions = [["PASS"] for _ in positions]
    available = []
    for i, pos in enumerate(positions):
        shed = min(SHED_TILES, key=lambda q: (dist(pos, q), q))
        if inv_total(invs[i]) and (pos in SHED_TILES or remaining <= dist(pos, shed) + 2):
            actions[i] = ["DROP"] if pos in SHED_TILES else step_toward(pos, shed)
        else:
            available.append(i)
    jobs = _terminal_jobs(obs, me)
    # One actor per tile per turn; on the following turn its next service is free.
    best = {}
    for job in jobs:
        if job[1] not in best or job[0] > best[job[1]][0]:
            best[job[1]] = job
    jobs = sorted(best.values(), key=lambda job: (-job[0], job[1]))
    weights = []
    for row, idx in enumerate(available):
        pos = positions[idx]
        values = []
        for value, target, action in jobs:
            travel = dist(pos, target)
            homeward = min(dist(target, q) for q in SHED_TILES)
            # Units act before the market: forecast DROP inventory in SELL orders.
            if travel + 1 + homeward + 1 > remaining:
                values.append(_IMPOSSIBLE)
            else:
                values.append(int(1000 * value / (travel + 1 + homeward * 0.25)))
        values += [0 if owner == row else _IMPOSSIBLE for owner in range(len(available))]
        weights.append(values)
    assigned = _hungarian_max(weights) if weights else []
    for row, col in enumerate(assigned):
        idx = available[row]
        pos = positions[idx]
        if 0 <= col < len(jobs) and weights[row][col] > 0:
            _, target, action = jobs[col]
            actions[idx] = action if pos == target else step_toward(pos, target)
        elif inv_total(invs[idx]):
            shed = min(SHED_TILES, key=lambda q: (dist(pos, q), q))
            actions[idx] = ["DROP"] if pos in SHED_TILES else step_toward(pos, shed)
    # Unit actions precede every market order. Reserve shed room in actor order
    # so simultaneous DROP actions do not discard cargo before sales clear it.
    shed_stock = private.get("shed", {}) or {}
    room = max(0, 100 - inv_total(shed_stock))
    can_clear = any(int(qty) > 0 and item in BASE
                    for item, qty in shed_stock.items())
    for idx, action in enumerate(actions):
        if action != ["DROP"]:
            continue
        quantity = inv_total(invs[idx])
        if quantity > room and remaining > 1 and can_clear:
            actions[idx] = ["PASS"]  # Sell existing stock; deliver next turn.
        else:
            room = max(0, room - quantity)
    return actions


def _terminal_market_orders(obs, me, private):
    # A SELL request is capped to actual shed stock by the engine. Including
    # carried stock makes each DROP immediately saleable, including the last act.
    stock = Counter(private.get("shed", {}) or {})
    for inv in private.get("inventories", []) or []:
        stock.update({item: int(n) for item, n in inv.items() if item in BASE})
    prices = (obs.get("market") or {}).get("prices", {})
    sells = [["SELL", item, int(n)] for item, n in stock.items() if item in BASE and n > 0]
    sells.sort(key=lambda order: (-order[2] * prices.get(order[1], BASE[order[1]]), order[1]))
    hires = []
    if int(obs.get("hour", 0)) <= 1:
        jobs = [job for job in _terminal_jobs(obs, me)
                if 2 * min(dist(job[1], p) for p in SHED_TILES) + 3
                <= TERMINAL_LAST_HOUR - int(obs.get("hour", 0)) + 1]
        # Budget about two collections per worker, and at most a quarter of the
        # available output. Empty or nearly empty farms need no extra payroll.
        desired = min(TERMINAL_MAX_HANDS, max(0, (len(jobs) + 1) // 2 - 1))
        budget = min(float(me.get("money", 0)), sum(job[0] for job in jobs) * 0.25)
        a, b = 1, 1
        for hired in range(desired):
            cost = a
            a, b = b, a + b
            if hired < int(me.get("hires_today", 0)):
                continue
            if cost > budget:
                break
            budget -= cost
            hires.append(["HIRE"])
    return (sells + hires)[:10]


