# is deliberately omitted -- choose_crops already discounts on the opponent's
# visible field counts (opp[] terms); this hunk adds only the missing
# market-timing half so the change stays attributable. Ladder-only EV (local
# league archetypes are static); guardrail = must not cost the animal_factory
# matchup.
OPP_SHADE_CLASSIFY_DAY = 5
OPP_SHADE_SELL_MAX = 0.30


def _opp_archetype(obs):
    """Coarse opponent classification from fully-public farm state, cheap enough
    to call once per market_orders. Returns: factory / wheatflood / premium /
    melon / passive / mixed (mixed = 'no confident read', the safe default)."""
    if obs.get("day", 0) < OPP_SHADE_CLASSIFY_DAY:
        return "mixed"
    of = obs["farms"][1 - obs["player"]]
    an = structs = 0
    crop = Counter()
    for row in of.get("tiles", []) or []:
        for t in row:
            if not isinstance(t, dict):
                continue
            if t.get("animal"):
                an += 1
            elif t.get("kind") == "PLANT":
                crop[t.get("crop")] += 1
            if t.get("kind") in ("COOP", "PASTURE"):
                structs += 1
    ct = sum(crop.values())
    if an >= 4 or structs >= 2:
        return "factory"
    if ct == 0 and an == 0:
        return "passive"
    if ct and crop.get("WHEAT", 0) / ct >= 0.5:
        return "wheatflood"
    if ct and crop.get("MELON", 0) / ct >= 0.4:
        return "melon"
    if ct and (crop.get("STRAWBERRY", 0) + crop.get("TOMATO", 0)) / ct >= 0.5 and an <= 1:
        return "premium"
    return "mixed"


